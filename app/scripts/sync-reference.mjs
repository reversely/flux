/**
 * The FM 21-76 PDF is a 3 MB scan that stays out of git (the pack system
 * will carry it later). This postinstall step copies it from the repo root
 * when present and writes src/data/reference.generated.ts so the reference
 * screen can require() it statically; without the file the export is null
 * and the screen explains how to install it.
 */
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePdf = join(appDir, '..', 'FM21-76_SurvivalManual.pdf');
const assetDir = join(appDir, 'assets', 'reference');
const assetPdf = join(assetDir, 'fm21-76.pdf');
const generatedPath = join(appDir, 'src', 'data', 'reference.generated.ts');

const header = '// Generated by scripts/sync-reference.mjs. Do not edit.\n';

if (existsSync(sourcePdf)) {
  mkdirSync(assetDir, { recursive: true });
  copyFileSync(sourcePdf, assetPdf);
  writeFileSync(
    generatedPath,
    `${header}export const referencePdf: number | null = require('../../assets/reference/fm21-76.pdf');\n`,
  );
  console.log('reference: copied FM 21-76 PDF into assets/reference');
} else {
  writeFileSync(generatedPath, `${header}export const referencePdf: number | null = null;\n`);
  console.log('reference: FM21-76_SurvivalManual.pdf not found at the repo root; screen will explain');
}
